"""Start the bridge automatically in every DianaIE session (opt-in).

DianaIE's embedded Python loads the user's site-packages folder (%APPDATA%\\Python\\Python37\\site-packages for
DIANA 10.5) at startup and runs the ``import`` lines of .pth files there. enable() writes diana_mcp_autostart.pth and
diana_mcp_autostart.py into that folder. The module returns at once in any other Python; inside DianaIE.exe it waits,
on a Win32 timer of the GUI thread, until DianaIE has set up its scripting namespace, then starts the bridge from this
installation, exactly like the one-line command for the command console. disable() removes both files.

    python -m diana_mcp autostart status|enable|disable

Every DianaIE session then listens on 127.0.0.1 with a random token stored in the user's local app data, like a
bridge started by hand. Set DIANA_MCP_AUTOSTART=0 to skip it for one DianaIE run.
"""
from __future__ import annotations

import ast
import os
import re
import sys
from pathlib import Path
from typing import Any

from . import config

MODULE = "diana_mcp_autostart"
MARKER = "# generated by diana-mcp autostart"

MODULE_TEMPLATE = '''\
{marker}: starts the diana-mcp bridge in every DianaIE session.
# Remove with "python -m diana_mcp autostart disable", or delete this file and diana_mcp_autostart.pth.
# Runs in every Python that uses this site-packages folder, so it returns at once outside DianaIE.exe.
import os
import sys

BRIDGE = {bridge!r}
SESSION_DIR = {session_dir!r}
_STATE = {{}}


def _log_error():
    try:
        import traceback
        if not os.path.isdir(SESSION_DIR):
            os.makedirs(SESSION_DIR)
        with open(os.path.join(SESSION_DIR, "autostart-error.log"), "a", encoding="utf-8") as f:
            f.write(traceback.format_exc() + "\\n")
    except Exception:
        pass


def _tick(hwnd, message, event_id, when):
    try:
        import time
        main = sys.modules.get("__main__")
        namespace = vars(main) if main is not None else {{}}
        ready = "diaVersion" in namespace and callable(namespace.get("logFileName"))
        if not ready and time.time() - _STATE["since"] < 900:
            return
        _STATE["user32"].KillTimer(None, _STATE["id"])
        if not ready:
            return
        import builtins
        running = getattr(builtins, "_diana_mcp_bridge", None)
        if running is not None and not running.closed:
            return
        os.environ.setdefault("DIANA_MCP_SESSION_DIR", SESSION_DIR)
        import runpy
        runpy.run_path(BRIDGE, init_globals={{"DIANA_NAMESPACE": namespace}}, run_name="diana_mcp_bridge")
    except Exception:
        _log_error()


def _install():
    if os.path.basename(sys.executable).lower() != "dianaie.exe":
        return
    if os.environ.get("DIANA_MCP_AUTOSTART", "1") == "0" or not os.path.isfile(BRIDGE):
        return
    try:
        import ctypes
        import ctypes.wintypes as wt
        import time
        user32 = ctypes.windll.user32
        proc_type = ctypes.WINFUNCTYPE(None, wt.HWND, wt.UINT, ctypes.c_size_t, wt.DWORD)
        user32.SetTimer.argtypes = [wt.HWND, ctypes.c_size_t, wt.UINT, proc_type]
        user32.SetTimer.restype = ctypes.c_size_t
        user32.KillTimer.argtypes = [wt.HWND, ctypes.c_size_t]
        _STATE.update(user32=user32, since=time.time(), callback=proc_type(_tick))
        _STATE["id"] = user32.SetTimer(None, 0, 500, _STATE["callback"])
    except Exception:
        _log_error()


_install()
'''


def python_tag(install: config.DianaInstall) -> str:
    """'Python37' for the Python embedded in this DIANA installation (from bin/python3X.dll)."""
    for dll in sorted((install.home / "bin").glob("python3*.dll")):
        match = re.fullmatch(r"python3(\d+)\.dll", dll.name, re.IGNORECASE)
        if match:
            return f"Python3{match.group(1)}"
    raise FileNotFoundError(f"no python3X.dll in {install.home / 'bin'}; cannot tell DianaIE's Python version")


def user_site(install: config.DianaInstall, base: Path | None = None) -> Path:
    """The user site-packages folder DianaIE's Python reads (PYTHONUSERBASE, else %APPDATA%\\Python)."""
    if base is None:
        env = os.environ.get("PYTHONUSERBASE")
        if env:
            base = Path(env)
        elif config.IS_WINDOWS:
            base = Path(os.environ.get("APPDATA") or Path.home() / "AppData" / "Roaming") / "Python"
        else:
            # DianaIE is a Windows process even when the MCP server runs on Linux.  Its user site therefore lives
            # inside the Wine prefix, not below the Unix account's ~/AppData directory.
            base = (config.wine_prefix() / "drive_c" / "users" / config.wine_user()
                    / "AppData" / "Roaming" / "Python")
    return base / python_tag(install) / "site-packages"


def _files(site: Path) -> tuple[Path, Path]:
    return site / f"{MODULE}.pth", site / f"{MODULE}.py"


def status(install: config.DianaInstall, base: Path | None = None) -> dict[str, Any]:
    site = user_site(install, base)
    pth, module = _files(site)
    enabled = pth.is_file() and module.is_file()
    info: dict[str, Any] = {"enabled": enabled, "site_packages": str(site)}
    if module.is_file():
        text = module.read_text(encoding="utf-8", errors="replace")
        match = re.search(r"^BRIDGE = (.+)$", text, re.MULTILINE)
        try:
            bridge = ast.literal_eval(match.group(1)) if match else None
        except (ValueError, SyntaxError):
            bridge = None
        info["bridge"] = bridge
        expected = {str(config.BRIDGE_SCRIPT)}
        try:
            expected.add(config.to_windows(config.BRIDGE_SCRIPT))
        except OSError:
            pass
        info["points_to_this_install"] = bool(bridge) and str(bridge) in expected
        info["generated_by_diana_mcp"] = MARKER in text
    error_log = config.sessions_dir() / "autostart-error.log"
    if error_log.is_file():
        info["error_log"] = str(error_log)
    return info


def enable(install: config.DianaInstall, base: Path | None = None, session_dir: Path | None = None) -> dict[str, Any]:
    site = user_site(install, base)
    pth, module = _files(site)
    if module.is_file() and MARKER not in module.read_text(encoding="utf-8", errors="replace"):
        raise FileExistsError(f"{module} exists and was not written by diana-mcp; not overwriting it")
    site.mkdir(parents=True, exist_ok=True)
    # The generated module is executed by DianaIE's Windows Python.  Convert host paths to the drive letters that
    # Wine exposes (for example /work/diana-mcp -> W:\\diana-mcp); on Windows this is an identity conversion.
    bridge = config.to_windows(config.BRIDGE_SCRIPT)
    sessions = config.to_windows(session_dir or config.sessions_dir())
    module.write_text(MODULE_TEMPLATE.format(marker=MARKER, bridge=bridge, session_dir=sessions), encoding="utf-8")
    pth.write_text(f"import {MODULE}\n", encoding="utf-8")
    return status(install, base)


def disable(install: config.DianaInstall, base: Path | None = None) -> dict[str, Any]:
    site = user_site(install, base)
    pth, module = _files(site)
    if module.is_file() and MARKER not in module.read_text(encoding="utf-8", errors="replace"):
        raise FileExistsError(f"{module} was not written by diana-mcp; not removing it")
    pth.unlink(missing_ok=True)
    module.unlink(missing_ok=True)
    return status(install, base)


def main(argv: list[str]) -> int:
    action = argv[0] if argv else "status"
    if action not in ("status", "enable", "disable"):
        print("usage: python -m diana_mcp autostart status|enable|disable", file=sys.stderr)
        return 2
    install = config.default_install()
    result = {"status": status, "enable": enable, "disable": disable}[action](install)
    for key, value in result.items():
        print(f"{key}: {value}")
    return 0
